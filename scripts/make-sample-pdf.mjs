import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'scripts', 'sample');
fs.mkdirSync(outDir, { recursive: true });

/** Escape the PDF string special characters. */
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');

function contentStream(lines) {
  const parts = ['BT', '/F1 26 Tf', '1 0 0 1 60 760 Tm', `(${esc(lines.title)}) Tj`, 'ET'];
  let y = 712;
  for (const l of lines.body) {
    const size = l.startsWith('#') ? 15 : 11;
    const text = l.replace(/^#+\s*/, '');
    parts.push('BT', `/F1 ${size} Tf`, `0.16 0.09 0.29 rg`, '1 0 0 1 60 ' + y + ' Tm', `(${esc(text)}) Tj`, 'ET');
    y -= l.startsWith('#') ? 34 : 22;
    if (y < 60) break;
  }
  return parts.join('\n');
}

function buildPdf(pages) {
  const objects = [];
  const add = (body) => {
    objects.push(body);
    return objects.length; // 1-based object number
  };

  // 1: catalog (filled in later), 2: pages, 3: font
  const catalogId = 1;
  const pagesId = 2;
  const fontId = 3;

  const pageIds = [];
  const contentIds = [];
  for (let i = 0; i < pages.length; i++) {
    pageIds.push(4 + i * 2);
    contentIds.push(5 + i * 2);
  }

  // Build in a fixed order: catalog, pages, font, then (page, content) pairs.
  const bodies = [];
  bodies[catalogId - 1] = `<< /Type /Catalog /Pages ${pagesId} 0 R >>`;
  bodies[pagesId - 1] = `<< /Type /Pages /Kids [${pageIds.map((p) => `${p} 0 R`).join(' ')}] /Count ${pages.length} >>`;
  bodies[fontId - 1] = `<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>`;

  pages.forEach((page, i) => {
    const stream = contentStream(page);
    bodies[pageIds[i] - 1] =
      `<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 595 842] ` +
      `/Resources << /Font << /F1 ${fontId} 0 R >> >> /Contents ${contentIds[i]} 0 R >>`;
    bodies[contentIds[i] - 1] = `<< /Length ${Buffer.byteLength(stream, 'latin1')} >>\nstream\n${stream}\nendstream`;
  });

  let pdf = '%PDF-1.4\n%\xE2\xE3\xCF\xD3\n';
  const offsets = [];
  bodies.forEach((body, idx) => {
    offsets.push(Buffer.byteLength(pdf, 'latin1'));
    pdf += `${idx + 1} 0 obj\n${body}\nendobj\n`;
  });
  const xrefStart = Buffer.byteLength(pdf, 'latin1');
  pdf += `xref\n0 ${bodies.length + 1}\n0000000000 65535 f \n`;
  for (const off of offsets) pdf += `${String(off).padStart(10, '0')} 00000 n \n`;
  pdf += `trailer\n<< /Size ${bodies.length + 1} /Root ${catalogId} 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

  return Buffer.from(pdf, 'latin1');
}

